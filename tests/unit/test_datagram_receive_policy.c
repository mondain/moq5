#include <moq/control_d18.h>
#include "test_support.h"
#include <string.h>

static int test_literal_empty_normal(void)
{
    int failures = 0;
    const uint8_t full[] = {0x00, 7, 9, 3, 128};
    const uint8_t omitted[] = {0x0c, 7, 9};
    const uint8_t eog[] = {0x02, 7, 9, 3, 128};
    const uint8_t props[] = {0x01, 7, 9, 3, 128, 2, 2, 9};
    const moq_bytes_t rows[] = {{full, sizeof(full)}, {omitted, sizeof(omitted)},
        {eog, sizeof(eog)}, {props, sizeof(props)}};
    for (size_t i = 0; i < sizeof(rows) / sizeof(rows[0]); ++i) {
        moq_d18_object_datagram_t out;
        moq_result_t rc = moq_d18_decode_object_datagram(rows[i].data, rows[i].len, &out);
        MOQ_TEST_CHECK_EQ_INT(rc, MOQ_OK);
        if (rc != MOQ_OK) continue;
        MOQ_TEST_CHECK(!out.is_status && out.track_alias == 7 && out.group_id == 9);
        MOQ_TEST_CHECK(out.object_id == (i == 1 ? 0u : 3u));
        MOQ_TEST_CHECK(out.publisher_priority == 128 && out.default_priority == (i == 1));
        MOQ_TEST_CHECK(out.end_of_group == (i == 2) && out.has_properties == (i == 3));
        MOQ_TEST_CHECK(out.payload_len == 0 && out.payload == rows[i].data + rows[i].len);
        if (i == 3)
            MOQ_TEST_CHECK(out.properties == props + 6 && out.properties_len == 2 &&
                           memcmp(out.properties, props + 6, 2) == 0);
    }
    MOQ_TEST_PASS("datagram_policy.literal_empty_normal_forms");
    return failures;
}

static int test_literal_padding_discard(void)
{
    int failures = 0;
    /* vi64(0x132b3e29), independently spelled rather than generated by codec. */
    const uint8_t none[] = {0xf0, 0x13, 0x2b, 0x3e, 0x29};
    const uint8_t zero[] = {0xf0, 0x13, 0x2b, 0x3e, 0x29, 0, 0, 0};
    const uint8_t nonzero[] = {0xf0, 0x13, 0x2b, 0x3e, 0x29, 0xff, 0x80, 1, 0};
    const moq_bytes_t rows[] = {{none, sizeof(none)}, {zero, sizeof(zero)},
        {nonzero, sizeof(nonzero)}};
    for (size_t i = 0; i < sizeof(rows) / sizeof(rows[0]); ++i) {
        moq_d18_object_datagram_t out;
        memset(&out, 0xa5, sizeof(out));
        MOQ_TEST_CHECK_EQ_INT(moq_d18_decode_object_datagram(rows[i].data, rows[i].len, &out), MOQ_DONE);
        MOQ_TEST_CHECK(!out.payload && !out.payload_len && !out.properties &&
                       !out.properties_len && !out.is_status);
    }
    MOQ_TEST_PASS("datagram_policy.literal_padding_discard_all_bytes");
    return failures;
}

static int test_literal_payload_and_status(void)
{
    int failures = 0;
    const uint8_t payload[] = {0x00, 7, 9, 3, 128, 0xaa, 0xbb};
    moq_d18_object_datagram_t out;
    moq_result_t rc = moq_d18_decode_object_datagram(payload, sizeof(payload), &out);
    MOQ_TEST_CHECK_EQ_INT(rc, MOQ_OK);
    if (rc == MOQ_OK)
        MOQ_TEST_CHECK(!out.is_status && out.payload_len == 2 && out.payload == payload + 5 &&
                       memcmp(out.payload, payload + 5, 2) == 0);
    const uint8_t statuses[][6] = {
        {0x20, 7, 9, 3, 128, 0}, {0x20, 7, 9, 3, 128, 3}, {0x20, 7, 9, 3, 128, 4}};
    const uint64_t expected[] = {MOQ_OBJECT_STATUS_NORMAL, MOQ_OBJECT_STATUS_END_OF_GROUP,
        MOQ_OBJECT_STATUS_END_OF_TRACK};
    for (size_t i = 0; i < sizeof(statuses) / sizeof(statuses[0]); ++i) {
        rc = moq_d18_decode_object_datagram(statuses[i], sizeof(statuses[i]), &out);
        MOQ_TEST_CHECK_EQ_INT(rc, MOQ_OK);
        if (rc == MOQ_OK)
            MOQ_TEST_CHECK(out.is_status && out.object_status == expected[i] &&
                           !out.payload && !out.payload_len && !out.end_of_group);
    }
    const uint8_t normal_props[] = {0x21, 7, 9, 3, 128, 2, 2, 9, 0};
    rc = moq_d18_decode_object_datagram(normal_props, sizeof(normal_props), &out);
    MOQ_TEST_CHECK_EQ_INT(rc, MOQ_OK);
    if (rc == MOQ_OK)
        MOQ_TEST_CHECK(out.is_status && out.object_status == MOQ_OBJECT_STATUS_NORMAL &&
                       out.has_properties && out.properties == normal_props + 6 &&
                       out.properties_len == 2 && !out.payload && !out.payload_len);
    MOQ_TEST_PASS("datagram_policy.literal_payload_and_status_forms");
    return failures;
}

static int test_existing_refusals(void)
{
    int failures = 0;
    const struct { uint8_t bytes[10]; size_t len; } rows[] = {
        {{0x10}, 1}, {{0x40}, 1}, {{0x30}, 1}, {{0x22}, 1},
        {{0x00}, 1}, {{0x00, 7}, 2}, {{0x00, 7, 9}, 3}, {{0x00, 7, 9, 3}, 4},
        {{0x20, 7, 9, 3, 128}, 5}, {{0x20, 7, 9, 3, 128, 0x80}, 6},
        {{0x20, 7, 9, 3, 128, 0, 0xaa}, 7}, {{0x20, 7, 9, 3, 128, 1}, 6},
        {{0x01, 7, 9, 3, 128, 0}, 6}, {{0x01, 7, 9, 3, 128, 2, 2}, 7},
        {{0x21, 7, 9, 3, 128, 2, 2, 9, 3}, 9},
        {{0x21, 7, 9, 3, 128, 2, 2, 9, 4}, 9},
        {{0xf0, 0x13, 0x2b, 0x3e}, 4}};
    for (size_t i = 0; i < sizeof(rows) / sizeof(rows[0]); ++i) {
        moq_d18_object_datagram_t out;
        MOQ_TEST_CHECK_EQ_INT(moq_d18_decode_object_datagram(rows[i].bytes, rows[i].len, &out), MOQ_ERR_PROTO);
    }
    MOQ_TEST_PASS("datagram_policy.existing_type_header_status_property_refusals");
    return failures;
}

static int test_encode_empty_normal(void)
{
    int failures = 0;
    const uint8_t expected[] = {0x00, 7, 9, 3, 128};
    uint8_t sentinel = 0x52;
    for (size_t i = 0; i < 2; ++i) {
        moq_d18_object_datagram_t in = {.track_alias = 7, .group_id = 9,
            .object_id = 3, .publisher_priority = 128, .payload = i ? &sentinel : NULL};
        uint8_t bytes[32];
        moq_buf_writer_t w;
        moq_buf_writer_init(&w, bytes, sizeof(bytes));
        moq_result_t rc = moq_d18_encode_object_datagram(&w, &in);
        MOQ_TEST_CHECK_EQ_INT(rc, MOQ_OK);
        if (rc == MOQ_OK) {
            MOQ_TEST_CHECK(w.pos == sizeof(expected) && memcmp(bytes, expected, sizeof(expected)) == 0);
            moq_d18_object_datagram_t out;
            rc = moq_d18_decode_object_datagram(bytes, w.pos, &out);
            MOQ_TEST_CHECK_EQ_INT(rc, MOQ_OK);
            if (rc == MOQ_OK) MOQ_TEST_CHECK(!out.is_status && out.payload_len == 0);
        }
    }
    moq_d18_object_datagram_t invalid = {.track_alias = 7, .group_id = 9,
        .object_id = 3, .publisher_priority = 128, .payload_len = 1};
    uint8_t bytes[32];
    moq_buf_writer_t w;
    moq_buf_writer_init(&w, bytes, sizeof(bytes));
    MOQ_TEST_CHECK_EQ_INT(moq_d18_encode_object_datagram(&w, &invalid), MOQ_ERR_INVAL);
    MOQ_TEST_CHECK(w.pos == 0);
    MOQ_TEST_PASS("datagram_policy.encode_empty_normal_not_terminal_status");
    return failures;
}

int main(void)
{
    int failures = test_literal_empty_normal();
    failures += test_literal_padding_discard();
    failures += test_literal_payload_and_status();
    failures += test_existing_refusals();
    failures += test_encode_empty_normal();
    return failures ? 1 : 0;
}
